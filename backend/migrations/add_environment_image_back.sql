-- =========================================================
-- add_environment_image_back.sql
-- 为环境资产添加背面图字段
-- 用途：环境图生成时同时输出「正面 + 180° 反向视角」两张图，
--       作为后续全景/场景图生成的双向参考锚点，维持画风一致性。
-- =========================================================

ALTER TABLE environments
ADD COLUMN image_back_url VARCHAR(500) DEFAULT NULL
COMMENT '环境背面图 URL（180° 反向视角），用于维持画风一致性';
